証明書ディスカバリは、ネットワークをスキャンしてサーバーやエンドポイントに配置されているTLS証明書を検出し、管理下のPKIインベントリと照合します。未追跡の証明書の特定、変更の検出、UCMの管理外にある期限切れ間近の証明書の監視に使用します。

