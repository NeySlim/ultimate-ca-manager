#!/usr/bin/env python3
"""Write the schema of a tagged UCM release as its models create it, with its migrations
recorded as applied: tests/fixtures/schema_v<version>_{sqlite,postgresql}.sql. Also writes
schema_v252_baseline_sqlite.sql, the 2.52 baseline that installations upgraded from it still
carry, read from the tag's migrations/000_baseline_v252.py.

    python3 scripts/schema_fixture.py v2.254-rc1 2.254

The tag's backend is extracted to a temporary directory and imported there, with its
configuration file loader switched off: nothing is read from an installation and no
database is opened. The registry lists every migration file of the tag, as the fresh
install of that release records it (mark_all_applied), on both backends.
"""
import ast
import io
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FIXTURES = REPO / 'backend' / 'tests' / 'fixtures'

# Runs inside the extracted backend: prints the fixture of one dialect on stdout
_DUMP = r'''
import sys
import dotenv
dotenv.load_dotenv = lambda *args, **kwargs: False
sys.path.insert(0, '.')
from pathlib import Path
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.schema import CreateIndex, CreateTable
import models  # noqa: F401
from models import db
# The tables app.py creates on a fresh install beyond the models package
import models.rbac, models.sso, models.policy, models.hsm  # noqa: E401,F401
import services.webhook_service  # noqa: F401
import migration_runner

name, version, tag = sys.argv[1], sys.argv[2], sys.argv[3]
dialect = postgresql.dialect() if name == 'postgresql' else sqlite.dialect()
out = [f"-- Schema of UCM {version}, the 3.0 upgrade pivot, as its models create it ({name}), with its",
       f"-- migrations recorded as applied. Generated from the {tag} tag by scripts/schema_fixture.py;",
       "-- never edited by hand.", ""]
for table in db.metadata.sorted_tables:
    out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
    out.append("")
    for index in sorted(table.indexes, key=lambda i: i.name or ""):
        out.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        out.append("")
ddl = migration_runner._DDL_PG if name == 'postgresql' else migration_runner._DDL_SQLITE
out.append(" ".join(ddl.split()) + ";")
for stem in migration_runner._list_migration_names():
    out.append(f"INSERT INTO _migrations (name) VALUES ('{stem}');")
print("\n".join(out))
'''


def baseline(tag: str) -> None:
    """The SCHEMA_SQL literal of the tag's baseline migration, read without running it."""
    source = subprocess.run(['git', '-C', str(REPO), 'show', f'{tag}:backend/migrations/000_baseline_v252.py'],
                            check=True, capture_output=True, text=True).stdout
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign) and [t.id for t in node.targets if isinstance(t, ast.Name)] == ['SCHEMA_SQL']:
            header = (f"-- Baseline schema of UCM 2.52 (migrations/000_baseline_v252.py of the {tag} tag), which "
                      "installations\n-- upgraded from it still carry. Generated by scripts/schema_fixture.py; "
                      "never edited by hand.\n")
            (FIXTURES / 'schema_v252_baseline_sqlite.sql').write_text(header + ast.literal_eval(node.value))
            return
    sys.exit(f'no SCHEMA_SQL in the baseline of {tag}')


def main(tag: str, version: str) -> None:
    archive = subprocess.run(['git', '-C', str(REPO), 'archive', tag, 'backend'],
                             check=True, capture_output=True).stdout
    with tempfile.TemporaryDirectory() as tmp:
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            tar.extractall(tmp, filter='data')
        backend = Path(tmp) / 'backend'
        env = {'PATH': '/usr/bin:/bin', 'DATA_DIR': str(Path(tmp) / 'data'), 'UCM_ENV': 'test',
               'SECRET_KEY': 'schema-fixture', 'DATABASE_URL': f"sqlite:///{Path(tmp) / 'unused.db'}"}
        for name in ('sqlite', 'postgresql'):
            dump = subprocess.run([sys.executable, '-c', _DUMP, name, version, tag], cwd=backend,
                                  env=env, check=True, capture_output=True, text=True).stdout
            (FIXTURES / f'schema_v{version.replace(".", "")}_{name}.sql').write_text(dump)
    baseline(tag)


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
